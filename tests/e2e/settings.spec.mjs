import { test, expect, _electron as electron } from '@playwright/test';
import { readFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import YAML from 'yaml';
import { desktopFixture } from './fixture.mjs';
import { availablePort } from '../../electron/core.mjs';

test('settings apply live LAN/port changes and persist startup choices without application proxy', async () => {
  const { directory, port } = await desktopFixture('desk-settings-');
  const env = { ...process.env, LUMA_TEST_MODE: '1', LUMA_TEST_TRAY: '1', LUMA_DATA_DIR: directory };
  delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL;
  const launch = process.env.LUMA_PACKAGED_APP ? { executablePath: process.env.LUMA_PACKAGED_APP, args: [], env } : { args: ['.'], env };
  let app;
  const source = http.createServer((req, res) => res.end('settings-proxy-ok'));
  await new Promise(resolve => source.listen(0, '127.0.0.1', resolve));
  try {
    app = await electron.launch(launch);
    let page = await app.firstWindow();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await expect(page.getByRole('button', { name: '停止内核', exact: true })).toBeVisible();
    await page.getByRole('navigation').getByRole('button', { name: '设置', exact: true }).click();
    await expect(page.getByRole('heading', { name: '网络设置', exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: '代理设置', exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: '启动设置', exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: '数据目录', exact: true })).toBeVisible();
    await expect(page.getByText('TUN', { exact: false })).toHaveCount(0);
    await expect(page.getByText('应用代理', { exact: true })).toHaveCount(0);
    expect(await app.evaluate(({ app }) => app.lumaTest.menu().getMenuItemById('application-proxy') === null)).toBe(true);
    expect(await page.evaluate(() => ['availableApplications', 'addApplication', 'setApplicationProxy', 'removeApplication', 'launchApplication'].some(key => key in window.luma))).toBe(false);
    expect(await app.evaluate(({ app }) => app.lumaTest.menu().getMenuItemById('tun') === null)).toBe(true);
    await expect(page.getByRole('switch', { name: '自动启动内核', exact: true })).toBeChecked();
    await page.getByRole('switch', { name: '允许局域网连接', exact: true }).click();
    await expect(page.getByRole('switch', { name: '允许局域网连接', exact: true })).toBeChecked();
    const newPort = await availablePort();
    await page.getByLabel('代理端口', { exact: true }).fill(String(newPort));
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await expect.poll(() => page.evaluate(() => window.luma.state().then(s => s.port))).toBe(newPort);
    await expect.poll(async () => YAML.parse(await readFile(path.join(directory, 'runtime.yaml'), 'utf8'))['mixed-port']).toBe(newPort);
    const runtime = YAML.parse(await readFile(path.join(directory, 'runtime.yaml'), 'utf8'));
    expect(runtime['allow-lan']).toBe(true); expect(runtime['bind-address']).toBe('*');
    expect(runtime['mixed-port']).toBe(newPort); expect(runtime['external-controller']).toMatch(/^127\.0\.0\.1:/);
    await expect.poll(() => availablePort(port)).toBe(port);
    const body = await new Promise((resolve, reject) => {
      const target = `http://127.0.0.1:${source.address().port}/test`;
      http.get({ host: '127.0.0.1', port: newPort, path: target, headers: { Host: `127.0.0.1:${source.address().port}` } }, response => { let body = ''; response.on('data', data => body += data); response.on('end', () => resolve(body)); }).on('error', reject);
    });
    expect(body).toBe('settings-proxy-ok');
    await page.getByRole('switch', { name: '允许局域网连接', exact: true }).click();
    await expect(page.getByRole('switch', { name: '允许局域网连接', exact: true })).not.toBeChecked();

    await page.getByRole('button', { name: '打开本地配置目录', exact: true }).click();
    await expect.poll(() => app.evaluate(({ app }) => app.lumaTest.openedDirectory())).toBe(path.join(directory, 'profiles'));
    await page.getByRole('button', { name: '打开本地应用目录', exact: true }).click();
    await expect.poll(() => app.evaluate(({ app }) => app.lumaTest.openedDirectory())).toBe(directory);
    await page.getByRole('switch', { name: '自动启动内核', exact: true }).click();
    await expect(page.getByRole('switch', { name: '自动启动内核', exact: true })).not.toBeChecked();
    expect(await page.evaluate(() => window.luma.state().then(s => s.running))).toBe(true);
    await page.getByRole('switch', { name: '自动启动 Luma', exact: true }).click();
    await expect(page.getByRole('switch', { name: '自动启动 Luma', exact: true })).toBeChecked();
    await mkdir('artifacts', { recursive: true });
    await page.locator('.page-scroll').evaluate(el => { el.scrollTop = 0; });
    await page.screenshot({ animations: 'disabled', path: 'artifacts/settings-top.png' });
    await page.locator('.page-scroll').evaluate(el => { el.scrollTop = el.scrollHeight; });
    await page.screenshot({ animations: 'disabled', path: 'artifacts/settings-directories.png' });
    expect(errors).toEqual([]);
    await app.close(); app = await electron.launch(launch); page = await app.firstWindow();
    await expect(page.getByRole('button', { name: '恢复运行', exact: true })).toBeVisible();
    const persisted = await page.evaluate(() => window.luma.state());
    expect(persisted.running).toBe(false); expect(persisted.autoStart).toBe(false);
    expect(persisted.port).toBe(newPort); expect(persisted.launchAtLogin).toBe(true);
    expect(persisted).not.toHaveProperty('applicationProxies');
    await page.getByRole('navigation').getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('switch', { name: '自动启动内核', exact: true }).click();
    await expect(page.getByRole('switch', { name: '自动启动内核', exact: true })).toBeChecked();
    await app.close(); app = await electron.launch(launch); page = await app.firstWindow();
    await expect(page.getByRole('button', { name: '停止内核', exact: true })).toBeVisible();
    expect(YAML.parse(await readFile(path.join(directory, 'runtime.yaml'), 'utf8'))['tcp-concurrent']).toBe(true);
  } finally { await app?.close(); await new Promise(resolve => source.close(resolve)); await rm(directory, { recursive: true, force: true }); }
});
