import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import { Store } from '../electron/store.mjs';
import { Core, availablePort } from '../electron/core.mjs';
import { DEFAULT_PROFILE } from '../electron/config.mjs';

test('real mihomo: HTTP proxy routing, authenticated API, mode changes, config reload and lifecycle', { timeout: 90000 }, async t => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'luma core % & '));
  const store = await new Store(directory).init(); store.state.port = await availablePort();
  const platform = { darwin: 'mac', win32: 'win', linux: 'linux' }[process.platform];
  let unexpectedExit = 0;
  const core = new Core({ binary: path.resolve(`resources/core/${platform}-${process.arch}/mihomo${process.platform === 'win32' ? '.exe' : ''}`), directory, store, onExit: () => { unexpectedExit++; } });
  const origin = http.createServer((req, res) => res.end('luma-proxy-proxy-ok'));
  await new Promise(r => origin.listen(0, '127.0.0.1', r));
  t.after(async () => { await core.stop(); await new Promise(r => origin.close(r)); await rm(directory, { recursive: true, force: true }); });
  assert.equal(await core.detect(), true, 'Download the core before running tests');
  await core.start(); assert.equal(core.running, true);
  const unauthenticated = await fetch(`http://127.0.0.1:${core.controllerPort}/version`); assert.equal(unauthenticated.status, 401);
  assert.equal((await core.request('/version')).version, 'v1.19.32');
  assert.equal((await core.request('/configs'))['tcp-concurrent'], true);
  const proxied = () => new Promise((resolve, reject) => {
    const req = http.get({ host: '127.0.0.1', port: store.state.port, headers: { Host: `127.0.0.1:${origin.address().port}` }, path: `http://127.0.0.1:${origin.address().port}/test`, timeout: 5000 }, res => { let body = ''; res.on('data', chunk => body += chunk); res.on('end', () => resolve({ status: res.statusCode, body })); });
    req.on('error', reject); req.on('timeout', () => req.destroy(new Error('timeout')));
  });
  assert.deepEqual(await proxied(), { status: 200, body: 'luma-proxy-proxy-ok' }, core.logs.map(log => log.message.replaceAll(core.secret, '[redacted]')).join('\n'));
  await core.request('/configs', { method: 'PATCH', body: JSON.stringify({ mode: 'global' }) });
  assert.equal((await core.request('/configs')).mode, 'global');
  await core.apply(DEFAULT_PROFILE); assert.equal((await core.request('/configs')).mode, 'rule');
  await core.request(`/proxies/${encodeURIComponent('节点选择')}`, { method: 'PUT', body: JSON.stringify({ name: 'REJECT' }) });
  const rejected = await proxied().catch(() => ({ status: 0 })); assert.notEqual(rejected.status, 200);
  const snapshot = await core.snapshot(); assert.ok(snapshot.downloadTotal > 0);
  for (let i = 0; i < 25 && core.memory === 0; i++) await new Promise(r => setTimeout(r, 100));
  assert.ok((await core.snapshot()).memory > 0, 'real memory stream must update the overview');
  await assert.rejects(core.apply('proxies: [{name: invalid, type: no-such-protocol}]'), /校验失败/);
  assert.equal(core.running, true, 'invalid configuration must leave the running core intact');
  await assert.rejects(availablePort(store.state.port), /已被占用/);
  await core.stop(); assert.equal(core.running, false); assert.equal(unexpectedExit, 0);
  await core.start(); await core.stop(); assert.equal(unexpectedExit, 0);
});
